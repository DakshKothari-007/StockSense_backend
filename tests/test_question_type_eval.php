// Evaluation metrics structure
$results = [];
$totalTP = 0;
$totalFP = 0;
$totalTN = 0;
$totalFN = 0;

$langNames = [
    'en' => 'English',
    'hi' => 'Hindi (Devanagari)',
    'ta' => 'Tamil (Script)',
    'hinglish' => 'Hinglish',
    'tanglish' => 'Tanglish'
];

foreach ($testData as $lang => $types) {
    $tp = 0; // Expected Advice, Predicted Advice
    $fn = 0; // Expected Advice, Predicted Lookup
    $tn = 0; // Expected Lookup, Predicted Lookup
    $fp = 0; // Expected Lookup, Predicted Advice
    
    $falsePositives = [];
    $falseNegatives = [];

    // Test Advice Phrases
    foreach ($types['advice'] as $q) {
        $norm = IntentEngine::normalize($q);
        $res = IntentEngine::classifyQuestionType($q, $norm, true, false);
        $predicted = $res['type'];
        
        // Advice should resolve to advice
        if ($predicted === 'advice') {
            $tp++;
        } else {
            $fn++;
            $falseNegatives[] = [
                'query' => $q,
                'predicted' => $predicted,
                'confidence' => $res['confidence'],
                'source' => $res['source']
            ];
        }
    }

    // Test Lookup Phrases
    foreach ($types['lookup'] as $q) {
        $norm = IntentEngine::normalize($q);
        $res = IntentEngine::classifyQuestionType($q, $norm, true, false);
        $predicted = $res['type'];
        
        // Lookup, conversation, general_knowledge, safety count as not advice (pure lookup control)
        if ($predicted === 'lookup' || $predicted === 'conversation' || $predicted === 'general_knowledge') {
            $tn++;
        } else {
            $fp++;
            $falsePositives[] = [
                'query' => $q,
                'predicted' => $predicted,
                'confidence' => $res['confidence'],
                'source' => $res['source']
            ];
        }
    }

    $totalQueries = $tp + $fn + $tn + $fp;
    $accuracy = (($tp + $tn) / $totalQueries) * 100;
    $precision = ($tp + $fp) > 0 ? ($tp / ($tp + $fp)) * 100 : 0;
    $recall = ($tp + $fn) > 0 ? ($tp / ($tp + $fn)) * 100 : 0;
    $f1 = ($precision + $recall) > 0 ? (2 * $precision * $recall) / ($precision + $recall) : 0;

    $results[$lang] = [
        'name' => $langNames[$lang],
        'total' => $totalQueries,
        'tp' => $tp,
        'fn' => $fn,
        'tn' => $tn,
        'fp' => $fp,
        'accuracy' => $accuracy,
        'precision' => $precision,
        'recall' => $recall,
        'f1' => $f1,
        'falsePositives' => $falsePositives,
        'falseNegatives' => $falseNegatives
    ];

    $totalTP += $tp;
    $totalFP += $fp;
    $totalTN += $tn;
    $totalFN += $fn;
}

$grandTotal = $totalTP + $totalFP + $totalTN + $totalFN;
$overallAccuracy = (($totalTP + $totalTN) / $grandTotal) * 100;

